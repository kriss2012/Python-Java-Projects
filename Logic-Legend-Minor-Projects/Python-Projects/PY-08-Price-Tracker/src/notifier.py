"""
Logic Legend - PY-08 Price Tracker with Web Scraping
Email Notification & Alert Dispatcher (SMTP & Simulation)
"""

import os
import smtplib
from email.mime.text import MIMEText

class Notifier:
    def __init__(self, db):
        self.db = db
        self.smtp_server = os.environ.get("SMTP_SERVER", "smtp.gmail.com")
        self.smtp_port = int(os.environ.get("SMTP_PORT", 587))
        self.sender_email = os.environ.get("SENDER_EMAIL", "").strip()
        self.sender_password = os.environ.get("SENDER_PASSWORD", "").strip()
        self.recipient_email = os.environ.get("RECIPIENT_EMAIL", "student@logiclegend.edu").strip()
        self.simulate_mode = os.environ.get("SIMULATE_EMAIL", "true").lower() == "true" or not self.sender_email

    def send_price_drop_alert(self, product_id, title, current_price, target_price, url):
        """Dispatches an alert when price drops to or below target threshold."""
        subject = f"🚨 PRICE DROP ALERT: {title[:40]} is now ₹{current_price:,.2f}!"
        body = f"""Hello,

Great news! The product you are monitoring has dropped below your configured price threshold.

Product Title : {title}
Current Price : ₹ {current_price:,.2f}
Target Price  : ₹ {target_price:,.2f}
Savings       : ₹ {(target_price - current_price):,.2f}
Store Link    : {url}

Happy Shopping!
Generated by Logic Legend PY-08 Price Tracker
"""
        # If simulated or credentials absent
        if self.simulate_mode:
            self._log_alert(product_id, current_price, target_price, self.recipient_email, status="SIMULATED")
            return {
                "success": True,
                "mode": "SIMULATED",
                "message": f"[SIMULATION] Email alert generated for '{title}' (Price: ₹{current_price} <= Target: ₹{target_price})."
            }

        try:
            msg = MIMEText(body)
            msg["Subject"] = subject
            msg["From"] = self.sender_email
            msg["To"] = self.recipient_email

            with smtplib.SMTP(self.smtp_server, self.smtp_port, timeout=8) as server:
                server.starttls()
                server.login(self.sender_email, self.sender_password)
                server.sendmail(self.sender_email, [self.recipient_email], msg.as_string())

            self._log_alert(product_id, current_price, target_price, self.recipient_email, status="SENT")
            return {"success": True, "mode": "LIVE_SMTP", "message": f"Live email alert dispatched to {self.recipient_email}."}

        except Exception as e:
            self._log_alert(product_id, current_price, target_price, self.recipient_email, status="FAILED")
            return {"success": False, "mode": "FAILED", "error": f"SMTP dispatch failed: {str(e)}"}

    def _log_alert(self, product_id, current_price, target_price, recipient, status):
        with self.db.get_connection() as conn:
            cursor = conn.cursor()
            cursor.execute("""
                INSERT INTO alert_logs (product_id, trigger_price, target_price, recipient_email, status)
                VALUES (?, ?, ?, ?, ?)
            """, (product_id, current_price, target_price, recipient, status))
            conn.commit()

